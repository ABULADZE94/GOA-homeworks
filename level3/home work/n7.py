num1 = float(input("შეიყვანეთ პირველი რიცხვი: "))
num2 = float(input("შეიყვანეთ მეორე რიცხვი: "))
num3 = float(input("შეიყვანეთ მესამე რიცხვი: "))

# მაგალითისთვის გამოვიყენოთ პირველი ორი რიცხვის ოპერაციები მესამეზე
print(f"ჯამი: {num1 + num2 + num3}")
print(f"სხვაობა: {num1 - num2 - num3}")
print(f"ნამრავლი: {num1 * num2 * num3}")
print(f"გაყოფა: {(num1 / num2) / num3}")
print(f"მთელი გაყოფა: {(num1 // num2) // num3}")
print(f"ნაშთი: {num1 % num2}")
print(f"ხარისხი: {num1 ** num2}")