# ორი რიცხვის შემოტანა
num1 = float(input("შეიყვანეთ პირველი რიცხვი: "))
num2 = float(input("შეიყვანეთ მეორე რიცხვი: "))

# ოპერაციების შესრულება და გამოტანა
print(f"{num1} + {num2} = {num1 + num2}")       # მიმატება
print(f"{num1} - {num2} = {num1 - num2}")       # გამოკლება
print(f"{num1} * {num2} = {num1 * num2}")       # გამრავლება
print(f"{num1} / {num2} = {num1 / num2}")       # გაყოფა
print(f"{num1} % {num2} = {num1 % num2}")       # ნაშთიანი გაყოფა
print(f"{num1} // {num2} = {num1 // num2}")     # მთელი გაყოფა
print(f"{num1} ** {num2} = {num1 ** num2}")     # ხარისხში აყვანა