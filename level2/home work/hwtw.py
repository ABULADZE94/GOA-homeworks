num1 = float(input("შეიყვანეთ პირველი რიცხვი: "))
num2 = float(input("შეიყვანეთ მეორე რიცხვი: "))
num3 = float(input("შეიყვანეთ მესამე რიცხვი: "))

# მაგალითისთვის გამოვიყენოთ პირველი ორი რიცხვის ოპერაციები მესამეზე
print("ჯამი: {num1 + num2 + num3}")
print("სხვაობა: {num1 - num2 - num3}")
print("ნამრავლი: {num1 * num2 * num3}")
print("გაყოფა: {(num1 / num2) / num3}")
print("მთელი გაყოფა: {(num1 // num2) // num3}")
print("ნაშთი: {num1 % num2}")
print("ხარისხი: {num1 ** num2}")