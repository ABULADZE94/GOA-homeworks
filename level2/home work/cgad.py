# +  (მიმატება) - კრებს ორ რიცხვს.
# -  (გამოკლება) - აკლებს მეორე რიცხვს პირველს.
# *  (გამრავლება) - ამრავლებს ორ რიცხვს ერთმანეთზე.
# /  (გაყოფა) - ყოფს რიცხვებს და ყოველთვის აბრუნებს ათწილადს (float).
# // (მთელი გაყოფა) - ყოფს რიცხვებს და აბრუნებს მხოლოდ მთელ ნაწილს (ჭრის ნაშთს).
# %  (ნაშთიანი გაყოფა) - აბრუნებს გაყოფის შედეგად მიღებულ ნაშთს.
# ** (ხარისხში აყვანა) - აჰყავს რიცხვი მითითებულ ხარისხში.