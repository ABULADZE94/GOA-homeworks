# 1. ვქმნით ცარიელ სიას
numbers = []

# 2. ვიყენებთ for ციკლს, რათა მომხმარებელს 5-ჯერ ვკითხოთ რიცხვი
print("გთხოვთ, შემოიყვანოთ 5 რიცხვი:")

for i in range(5):
    # მომხმარებლის მიერ შემოყვანილ ტექსტს ვაქცევთ მთელ რიცხვად (int)
    num = int(input(f"{i+1}-ე რიცხვი: "))
    
    # .append() ფუნქციით ვამატებთ მიღებულ რიცხვს სიის ბოლოში
    numbers.append(num)

# 3. ვბეჭდავთ მიღებულ სრულ სიას
print("\nთქვენ მიერ შევსებული სია არის:")
print(numbers)