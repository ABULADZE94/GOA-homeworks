# 1. ვქმნით ორ ცარიელ სიას
even_numbers = []  # ლუწებისთვის
odd_numbers = []   # კენტებისთვის

print("გთხოვთ, შემოიყვანოთ 10 რიცხვი:")

# 2. ვიყენებთ ციკლს 10 რიცხვის მისაღებად
for i in range(10):
    num = int(input(f"{i+1}-ე რიცხვი: "))
    
    # 3. ვამოწმებთ არის თუ არა რიცხვი ლუწი
    if num % 2 == 0:
        # თუ ნაშთი 2-ზე გაყოფისას არის 0, ვამატებთ ლუწების სიაში
        even_numbers.append(num)
    else:
        # სხვა შემთხვევაში (თუ ნაშთი არის 1), ვამატებთ კენტების სიაში
        odd_numbers.append(num)

# 4. ვბეჭდავთ შედეგებს
print("\n--- შედეგები ---")
print(f"ლუწი რიცხვების სია: {even_numbers}")
print(f"კენტი რიცხვების სია: {odd_numbers}")