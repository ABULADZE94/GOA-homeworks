# 1. LIST (სია)
# გამოიყენება მონაცემთა კოლექციის შესანახად. 
# სიაში ელემენტები დალაგებულია ინდექსების მიხედვით (ათვლა იწყება 0-დან),
# არის ცვლადი (შეგვიძლია შეცვლა) და ნებას გვაძლევს გვქონდეს დუბლიკატები.
fruits = ["apple", "banana", "cherry"]

# 2. .append() მეთოდი
# გამოიყენება სიის ბოლოში ახალი ელემენტის დასამატებლად.
# ის ყოველთვის ზრდის სიის ზომას ერთით და ამატებს ობიექტს ბოლოში.
fruits.append("orange") 
# შედეგი: ["apple", "banana", "cherry", "orange"]

# 3. .remove() მეთოდი
# გამოიყენება სიიდან კონკრეტული ელემენტის ამოსაშლელად მისი მნიშვნელობის მიხედვით.
# თუ სიაში რამდენიმე ერთნაირი ელემენტია, .remove() წაშლის მხოლოდ პირველს.
# შენიშვნა: თუ მითითებული ელემენტი სიაში არ არსებობს, ამოაგდებს შეცდომას (ValueError).
fruits.remove("banana") 
# შედეგი: ["apple", "cherry", "orange"]

# 4. len() ფუნქცია
# გამოიყენება სიის სიგრძის (ელემენტების რაოდენობის) გასაგებად.
# ის აბრუნებს მთელ რიცხვს (integer).
length_of_list = len(fruits) 
# შედეგი იქნება 3, რადგან ამ მომენტში სიაში 3 ელემენტია დარჩენილი.
print(length_of_list)