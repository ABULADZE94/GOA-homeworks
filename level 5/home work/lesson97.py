# მომხმარებელს ვთხოვთ ასაკის შემოყვანას
age = int(input("შემოიყვანეთ თქვენი ასაკი: "))

# ვეკითხებით სტუდენტური ბარათის შესახებ (კი/არა პასუხით)
has_card = input("გაქვთ სტუდენტური ბარათი? (კი/არა): ").lower()

# 1. პირობა: ასაკი < 18 ან აქვს ბარათი
if age < 18 or has_card == "კი":
    print("დანაზოგი გაქვს!")

# 2. პირობა: ასაკი 60+ და არ აქვს ბარათი
elif age >= 60 and has_card == "არა":
    print("პენსიონერის ფასდაკლება გაქვს!")

# 3. ყველა სხვა შემთხვევაში
else:
    print("ფასდაკლება არ გეკუთვნის.")